#!/usr/bin/env python3
"""Generate and check the vendored protobuf modules and type stubs.

``protoc`` emits snake_case modules and imports for the vendored schemas, while
this package uses CamelCase module names and absolute ``librespot.proto``
imports. It also emits ``*_pb2.pyi`` stubs because the generated ``*_pb2.py``
modules expose their message classes dynamically.

The checked-in files must be regenerated with the same ``grpcio-tools`` version
as the ``proto`` extra, otherwise ``--check`` will report differences.

Usage:
    uv run --extra proto python scripts/generate_proto_stubs.py
    uv run --extra proto python scripts/generate_proto_stubs.py --check
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PROTO_DIR = ROOT / "proto"
OUT_DIR = ROOT / "librespot" / "proto"
HEADER = "# Generated by scripts/generate_proto_stubs.py. Do not edit.\n"

FLAT_IMPORT = re.compile(r"^import ([a-z0-9_]+)_pb2 as (\w+)$", re.MULTILINE)
NESTED_IMPORT = re.compile(
    r"^from spotify\.login5\.v3(\.\w+)? import ([a-z0-9_]+)_pb2 as (\w+)$",
    re.MULTILINE,
)
BUILD_MODULE = re.compile(
    r"(_builder\.BuildTopDescriptorsAndMessages\(DESCRIPTOR, )'[^']+'(, _globals\))"
)


def camel_case(stem: str) -> str:
    return "".join(part.capitalize() for part in re.split(r"[_-]", stem))


def module_path(rel: Path, stem: str) -> str:
    return ".".join(["librespot", "proto", *rel.parent.parts, f"{camel_case(stem)}_pb2"])


def _rewrite(text: str, module: str) -> str:
    text = FLAT_IMPORT.sub(
        lambda m: f"import librespot.proto.{camel_case(m.group(1))}_pb2 as {m.group(2)}",
        text,
    )
    text = NESTED_IMPORT.sub(
        lambda m: (
            f"from librespot.proto.spotify.login5.v3{m.group(1) or ''} "
            f"import {camel_case(m.group(2))}_pb2 as {m.group(3)}"
        ),
        text,
    )
    return BUILD_MODULE.sub(lambda m: f"{m.group(1)}'{module}'{m.group(2)}", text)


def generate(target: Path) -> None:
    protos = sorted(PROTO_DIR.rglob("*.proto"))
    if not protos:
        raise SystemExit(f"no .proto files found under {PROTO_DIR}")

    with tempfile.TemporaryDirectory() as tmp:
        tmp_path = Path(tmp)
        subprocess.run(
            [
                sys.executable,
                "-m",
                "grpc_tools.protoc",
                f"-I{PROTO_DIR}",
                f"--python_out={tmp_path}",
                f"--pyi_out={tmp_path}",
                *(str(p.relative_to(PROTO_DIR)) for p in protos),
            ],
            cwd=ROOT,
            check=True,
        )

        for source in sorted(tmp_path.rglob("*_pb2.py")):
            rel = source.relative_to(tmp_path)
            stem = source.name.removesuffix("_pb2.py")
            destination = target / rel.parent / f"{camel_case(stem)}_pb2.py"
            destination.parent.mkdir(parents=True, exist_ok=True)
            destination.write_text(_rewrite(source.read_text(), module_path(rel, stem)))

        for source in sorted(tmp_path.rglob("*_pb2.pyi")):
            rel = source.relative_to(tmp_path)
            stem = source.name.removesuffix("_pb2.pyi")
            destination = target / rel.parent / f"{camel_case(stem)}_pb2.pyi"
            destination.parent.mkdir(parents=True, exist_ok=True)
            destination.write_text(HEADER + _rewrite(source.read_text(), module_path(rel, stem)))


def _generated_files(root: Path) -> dict[Path, Path]:
    files = {p.relative_to(root): p for p in root.rglob("*_pb2.py")}
    files.update({p.relative_to(root): p for p in root.rglob("*_pb2.pyi")})
    return files


def check(target: Path) -> int:
    with tempfile.TemporaryDirectory() as tmp:
        generated = Path(tmp) / "generated"
        generated.mkdir()
        generate(generated)
        expected = _generated_files(generated)
        actual = _generated_files(target)
        problems = []
        for rel in sorted(expected.keys() | actual.keys()):
            if rel not in actual:
                problems.append(f"missing: {rel}")
            elif rel not in expected:
                problems.append(f"stale: {rel}")
            elif expected[rel].read_bytes() != actual[rel].read_bytes():
                problems.append(f"out of date: {rel}")
        if problems:
            print("proto modules are out of date:", file=sys.stderr)
            print("\n".join(f"  {p}" for p in problems), file=sys.stderr)
            print("run: uv run --extra proto python scripts/generate_proto_stubs.py", file=sys.stderr)
            return 1
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify modules are up to date")
    args = parser.parse_args()
    if args.check:
        return check(OUT_DIR)
    generate(OUT_DIR)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
